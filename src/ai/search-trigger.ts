/**
 * Правила, по которым решаем, нужна ли свежая информация из интернета.
 *
 * Решаем правилами, а НЕ спрашивая модель. Схема с tool-calling («модель решает,
 * что нужен поиск, потом отвечает») стоит двух обращений к OpenRouter на один
 * вопрос, а у нас бесплатный тир ограничен числом запросов: 20 в минуту и
 * 50–1000 в сутки на весь бот. Правила чуть грубее, зато расход вдвое меньше.
 *
 * Ошибка в сторону лишнего поиска дешевле, чем в сторону устаревшего ответа:
 * лимит Tavily (1000 запросов в месяц) заведомо выше нашего дневного лимита
 * обращений к моделям.
 *
 * Живёт отдельно от клиента Tavily: функция чистая и не должна тянуть за собой
 * конфигурацию окружения — иначе её не проверить без реальных ключей.
 */

/** Явные маркеры «прямо сейчас». */
const TIME_MARKERS =
  /(сейчас|сегодня|вчера|на\s+данный\s+момент|в\s+данный\s+момент|актуальн|последн|свеж|нынешн|текущ|недавн|только\s+что|на\s+этой\s+неделе|в\s+этом\s+году)/;

/** Темы, которые устаревают всегда. */
const VOLATILE_TOPICS =
  /(новост|происходит|случилось|произошл|курс\s|курса|погод|цена|цены|стоимость|сколько\s+стоит|результат\s+матч|счёт\s+матч|расписани|концерт|тур\b|релиз|вышел|выйдет|выпустил|анонс|обновлени|санкц|выбор|президент|премьер)/;

/** Годы после обучения моделей — верный признак вопроса о свежем. */
const RECENT_YEAR = /\b(202[5-9]|203\d)\b/;

/** Прямая просьба посмотреть. */
const EXPLICIT_LOOKUP =
  /(погугли|загугли|найди\s+в\s+интернет|поищи|посмотри\s+в\s+интернет|проверь\s+в\s+интернет)/;

export function needsFreshInfo(text: string): boolean {
  const t = text.toLowerCase();
  return (
    EXPLICIT_LOOKUP.test(t) ||
    RECENT_YEAR.test(t) ||
    VOLATILE_TOPICS.test(t) ||
    (TIME_MARKERS.test(t) && t.length > 10)
  );
}
