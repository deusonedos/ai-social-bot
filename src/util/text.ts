/**
 * Reasoning-модели иногда отдают размышления прямо в content вместо отдельного
 * поля `reasoning`. Пользователю они не нужны — он ждёт ответ, а не протокол.
 *
 * Живёт в утилитах, а не в пайплайне: функция чистая и не должна тянуть за собой
 * конфигурацию окружения.
 */
export function stripReasoning(text: string): string {
  return text
    .replace(/<think>[\s\S]*?<\/think>/gi, '')
    .replace(/<reasoning>[\s\S]*?<\/reasoning>/gi, '')
    // Незакрытый тег означает, что модель уперлась в max_tokens посреди размышления.
    .replace(/<\/?(think|reasoning)>/gi, '')
    .trim();
}

/**
 * Приводит ответ модели к виду, пригодному для Telegram.
 *
 * Сообщения отправляются без parse_mode (любая некорректная разметка привела бы
 * к ошибке 400 и потере ответа целиком), поэтому вся разметка, которую модель
 * всё-таки выдала, до пользователя доезжает как мусорные символы: `**жирный**`
 * показывается со звёздочками, а не жирным.
 *
 * Отдельная беда — служебные маркеры ссылок вида 【1†L0-L3】: так некоторые модели
 * помечают цитаты из источников. Для пользователя это нечитаемый шум, тем более
 * что настоящий список ссылок мы добавляем сами.
 */
export function cleanForTelegram(text: string): string {
  return (
    text
      // Маркеры цитирования: 【1†L0-L3】, 【12:3†source】 и подобные.
      .replace(/【[^】]*】/g, '')
      // Строка «Источники: [1], [2], [3].» целиком — свой список ссылок мы
      // добавляем отдельно. Обязательно ДО вырезания номеров: иначе к этому
      // моменту от строки останется голое «Источники:» и правило не сработает.
      .replace(/^[ \t]*(источники|sources|ссылки)[ \t]*:[ \t]*(?:\[\d+\][\s,;.]*)+$/gim, '')
      // Сноски вида [1], [2,3] в тексте — ссылками они всё равно не были.
      .replace(/\s*\[\d+(?:\s*,\s*\d+)*\]/g, '')
      // Жирный и курсив: без parse_mode это просто звёздочки и подчёркивания.
      .replace(/\*\*([^*\n]+)\*\*/g, '$1')
      // У курсива содержимое не может начинаться или заканчиваться пробелом —
      // без этого условия правило съедало знаки умножения в «2 * 3 = 6».
      .replace(/(?<![\w*])\*(?!\s)([^*\n]+?)(?<!\s)\*(?![\w*])/g, '$1')
      .replace(/(?<![\w_])__(?!\s)([^_\n]+?)(?<!\s)__(?![\w_])/g, '$1')
      // Заголовки Markdown в чате смысла не имеют.
      .replace(/^#{1,6}\s+/gm, '')
      // Ограждения блоков кода: сам код оставляем, забор убираем.
      .replace(/^```[a-z]*\s*$/gim, '')
      .replace(/\n{3,}/g, '\n\n')
      .trim()
  );
}
