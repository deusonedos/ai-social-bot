/**
 * Грубая оценка токенов без токенизатора. Нам нужна не точность, а дешёвый
 * триггер «пора сворачивать историю»: точный подсчёт потребовал бы тянуть
 * токенизатор под каждую модель, а моделей у нас десяток и они меняются.
 *
 * ~3.2 символа на токен — компромисс между латиницей (~4) и кириллицей (~2.5),
 * с запасом в сторону переоценки.
 */
export function estimateTokens(text: string): number {
  return Math.ceil(text.length / 3.2);
}

